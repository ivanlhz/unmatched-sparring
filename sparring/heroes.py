"""HeroDef: what is specific to each hero, read from `data/heroes/<slug>.json`.

The file is generated by `tools/import_hero.py` from unmatched-memory (read only) and the hand-written overlay
`data/heroes/overlay/<slug>.json` (CardID sheet, fighter restrictions, tags, forms, counters,
triggers and passives). The engine only reads the generated HeroDef: it never depends on unmatched-memory at
game time.

Forms and counters: a counter counts the cards with a tag in a pile (today only the discard); the form
is `below` while the counter does not reach `threshold` and `at_or_above` from then on (Hellboy: 6 destinies).
Triggers and passives are loaded as data (dicts) and the engine interprets them by their `effect`; until step 8 of the
plan only the `attack_bonus` passive is wired."""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

from .board import DATA_DIR
from .cards import Card

HEROES_DIR = DATA_DIR / "heroes"
CARD_TYPES = ("attack", "defense", "versatile", "scheme")
DECK_SIZE = 30              # playing cards of a deck unless the HeroDef says otherwise (`deck.size`: Daredevil has 22)
DEFAULT_START_HAND = 5      # opening hand and end-of-turn hand limit of a hero whose card says nothing else
DEFAULT_HAND_LIMIT = 7


class HeroDataError(Exception):
    """The HeroDef is unusable for playing (missing or wrong); the message says what."""


@dataclass(frozen=True)
class SidekickDef:
    fid: str          # prefix of the fighter id: with count > 1 it is numbered (harpy1, harpy2, harpy3)
    name: str
    count: int
    hp: int
    move: int
    ranged: bool
    start_on_board: int | None = None     # how many start on the board; None = all, the rest start in reserve


@dataclass(frozen=True)
class FighterSpec:
    fid: str
    name: str
    hero: bool
    hp: int
    move: int
    ranged: bool
    on_board: bool = True                 # False: starts in reserve (off the board) until an effect summons it
    reach: int = 0                        # attack reach in spaces, zones ignored (Bullseye: 5); 0 = the usual melee / ranged rule


@dataclass(frozen=True)
class CounterDef:
    name: str
    pile: str         # "discard": where the cards are counted
    tag: str          # card tag that counts


@dataclass(frozen=True)
class FormDef:
    counter: str
    threshold: int
    below: str
    at_or_above: str

    def of(self, count: int) -> str:
        return self.at_or_above if count >= self.threshold else self.below


@dataclass(frozen=True)
class HeroDef:
    slug: str
    name: str
    fid: str
    hp: int
    move: int
    ranged: bool
    ability: str
    sidekicks: tuple[SidekickDef, ...]
    forms: FormDef | None
    counters: dict[str, CounterDef]
    triggers: tuple[dict, ...]
    passives: tuple[dict, ...]
    card_base: int | None
    cards: tuple[dict, ...]
    ai_profile: dict = field(default_factory=dict)    # per fighter group, computed at import (sparring/ai_profile.py)
    hand_start: int = DEFAULT_START_HAND              # opening hand (Michelangelo: 3)
    hand_max: int = DEFAULT_HAND_LIMIT                # most cards kept at the end of the turn (Michelangelo: 3)
    deck_size: int = DECK_SIZE                        # playing cards of the deck (the character card is not one): CardIDs card_base .. card_base + deck_size - 1
    reach_spaces: int = 0                             # the hero attacks anyone up to this many spaces away, zones ignored (Bullseye: 5); 0 = the usual rule
    tts: dict = field(default_factory=dict)           # how the save names what the hero shares with another variant (Yennefer & Triss): `bag_name`, `character_cards`, `character_card_id`; only tools/import_save.py reads it

    def fighter_profile(self, name: str) -> dict | None:
        """The AI profile of the fighter called `name` (hero or sidekick group), None when the HeroDef has none."""
        for p in self.ai_profile.values():
            if p["name"] == name:
                return p
        return None

    @property
    def fighter_names(self) -> set[str]:
        return {self.name, *(s.name for s in self.sidekicks)}

    def fighters(self) -> list[FighterSpec]:
        """Hero and sidekicks in placement order, with their fighter ids."""
        out = [FighterSpec(self.fid, self.name, True, self.hp, self.move, self.ranged, reach=self.reach_spaces)]
        for s in self.sidekicks:
            for i in range(1, s.count + 1):
                fid = f"{s.fid}{i}" if s.count > 1 else s.fid
                on_board = s.start_on_board is None or i <= s.start_on_board
                out.append(FighterSpec(fid, s.name, False, s.hp, s.move, s.ranged, on_board))
        return out

    def deck(self, shift: int = 0) -> list[Card]:
        """The hero's playing cards (30, or `deck_size`). `shift` moves every CardID by that many (a multiple of 100): TTS renumbers a deck's DeckID
        when it spawns next to another with the same one, and the table's cards then carry the shifted ids."""
        if self.card_base is None:
            raise HeroDataError(f"{self.slug}: deck without a CardID sheet or fighter restrictions (pending F08)")
        return [Card(self.card_base + shift + c["idx"], c["title"], c["fighter"], c["type"], c["value"], c["boost"],
                     c.get("text", ""), frozenset(c.get("tags", ()))) for c in self.cards]

    def attack_bonuses(self, form: str | None, fighter_is_hero: bool, maneuvered: bool = False) -> list[tuple[int, str]]:
        """(bonus, tag) of each `attack_bonus` passive active in that form (Hellboy: (2, 'ANUNG UN RAMA')).
        The tag is the form that activates it or, if the passive does not depend on the form, its id. A passive with
        `"unless": "maneuver"` is off once the owner has taken a Maneuver action this turn (`maneuvered`; Golden Bat)."""
        out = []
        for p in self.passives:
            if p.get("effect") != "attack_bonus" or p.get("form", form) != form:
                continue
            if maneuvered and p.get("unless") == "maneuver":
                continue
            if p.get("fighter", "hero") == "hero" and not fighter_is_hero:
                continue
            out.append((int(p["n"]), p.get("form") or p.get("id") or "pasiva"))
        return out

    def attack_bonus(self, form: str | None, fighter_is_hero: bool, maneuvered: bool = False) -> int:
        return sum(n for n, _ in self.attack_bonuses(form, fighter_is_hero, maneuvered))


def hero_path(slug: str, heroes_dir: Path = HEROES_DIR) -> Path:
    return heroes_dir / f"{slug}.json"


def _ranged(attack: str, where: str) -> bool:
    if attack not in ("melee", "range"):
        raise HeroDataError(f"{where}: unknown attack {attack!r} (melee or range)")
    return attack == "range"


def parse_hero(raw: dict, where: str = "hero") -> HeroDef:
    try:
        slug, name = raw["slug"], raw["name"]
        sidekicks = tuple(SidekickDef(s["fid"], s["name"], int(s["count"]), int(s["hp"]), int(s["move"]),
                                      _ranged(s["attack"], f"{where}: sidekick {s['name']}"),
                                      None if s.get("start_on_board") is None else int(s["start_on_board"]))
                          for s in raw.get("sidekicks", ()))
        counters = {k: CounterDef(k, v["pile"], v["tag"]) for k, v in (raw.get("counters") or {}).items()}
        f = raw.get("forms")
        forms = None if f is None else FormDef(f["counter"], int(f["threshold"]), f["below"], f["at_or_above"])
        deck = raw.get("deck") or {}
        hero = HeroDef(slug, name, raw["fid"], int(raw["hp"]), int(raw["move"]), _ranged(raw["attack"], where),
                       raw.get("ability") or "", sidekicks, forms, counters,
                       tuple(raw.get("triggers") or ()), tuple(raw.get("passives") or ()),
                       deck.get("card_base"), tuple(deck.get("cards") or ()), raw.get("ai_profile") or {},
                       int((raw.get("hand") or {}).get("start", DEFAULT_START_HAND)),
                       int((raw.get("hand") or {}).get("max", DEFAULT_HAND_LIMIT)),
                       int(deck.get("size", DECK_SIZE)),
                       int(raw.get("reach_spaces") or 0), dict(raw.get("tts") or {}))
    except (KeyError, TypeError, ValueError) as e:
        raise HeroDataError(f"{where}: invalid HeroDef ({e!r})") from None
    _validate(hero, where)
    return hero


def _validate(h: HeroDef, where: str) -> None:
    if h.hp <= 0 or h.move < 0:
        raise HeroDataError(f"{where}: invalid life or movement")
    if h.hand_start <= 0 or h.hand_max <= 0:
        raise HeroDataError(f"{where}: invalid hand size")
    if h.reach_spaces < 0:
        raise HeroDataError(f"{where}: invalid reach")
    if any(s.count <= 0 or s.hp <= 0 for s in h.sidekicks):
        raise HeroDataError(f"{where}: sidekick with an invalid count or life")
    fids = [f.fid for f in h.fighters()]
    if len(set(fids)) != len(fids):
        raise HeroDataError(f"{where}: repeated fighter ids {fids}")
    if h.forms is not None:
        if h.forms.counter not in h.counters:
            raise HeroDataError(f"{where}: the form uses counter {h.forms.counter!r}, which does not exist")
    for c in h.counters.values():
        if c.pile != "discard":
            raise HeroDataError(f"{where}: counter {c.name}: unknown pile {c.pile!r}")
    if h.card_base is None:
        return
    if len(h.cards) != h.deck_size:
        raise HeroDataError(f"{where}: the deck has {len(h.cards)} cards, not {h.deck_size}")
    idxs = [c.get("idx") for c in h.cards]
    if sorted(idxs) != list(range(h.deck_size)):
        raise HeroDataError(f"{where}: the sheet idx must be 0..{h.deck_size - 1} without repeats")
    allowed = h.fighter_names | {"any"}
    for c in h.cards:
        if c.get("type") not in CARD_TYPES:
            raise HeroDataError(f"{where}: {c.get('title')!r}: type {c.get('type')!r}")
        if c.get("fighter") not in allowed:
            raise HeroDataError(f"{where}: {c.get('title')!r}: restriction {c.get('fighter')!r} is not a fighter")
        if (c["type"] == "scheme") != (c.get("value") is None):
            raise HeroDataError(f"{where}: {c.get('title')!r}: only schemes go without a value")


@lru_cache(maxsize=None)
def load_hero(slug: str, heroes_dir: Path = HEROES_DIR) -> HeroDef:
    path = hero_path(slug, heroes_dir)
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except OSError:
        raise HeroDataError(f"no HeroDef for {slug!r}: {path} is missing") from None
    except ValueError as e:
        raise HeroDataError(f"{path}: invalid JSON ({e})") from None
    if raw.get("slug") != slug:
        raise HeroDataError(f"{path}: the file's slug is {raw.get('slug')!r}, not {slug!r}")
    return parse_hero(raw, str(path.name))


def available_heroes(heroes_dir: Path = HEROES_DIR) -> list[str]:
    return sorted(p.stem for p in heroes_dir.glob("*.json"))
