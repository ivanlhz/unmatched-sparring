from __future__ import annotations

import itertools
import json
import os
import queue
import socket
import threading
import time
from collections import deque
from typing import Callable

from ..i18n import t
from . import lua
from .lua import is_sendable

SEND_PORT = 39999
LISTEN_PORT = 39998
MSG_CUSTOM = 2
MSG_EXECUTE = 3
ALLOWED_OUT = frozenset({MSG_CUSTOM, MSG_EXECUTE})
WSAEADDRINUSE = 10048     # Windows: no ephemeral port free (the previous connections are still in TIME_WAIT)
PORT_RETRIES = 20
PORT_RETRY_WAIT = 0.25

IN_NEW_GAME, IN_PRINT, IN_ERROR, IN_CUSTOM, IN_RETURN, IN_SAVED = 1, 2, 3, 4, 5, 6


class UnsafeMessage(Exception):
    pass


class TTSLuaError(Exception):
    pass


class Listener:
    """TCP server TTS connects back to; one JSON message per connection."""

    def __init__(self, host: str = "127.0.0.1", port: int = LISTEN_PORT):
        self._srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self._srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self._srv.bind((host, port))
        self._srv.listen(8)
        self.port = self._srv.getsockname()[1]
        self.messages: "queue.Queue[dict]" = queue.Queue()
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._loop, daemon=True)
        self._thread.start()

    def _loop(self) -> None:
        self._srv.settimeout(0.1)
        while not self._stop.is_set():
            try:
                conn, _ = self._srv.accept()
            except socket.timeout:
                continue
            except OSError:
                break
            with conn:
                conn.settimeout(2.0)
                chunks = []
                try:
                    while (data := conn.recv(65536)):
                        chunks.append(data)
                except socket.timeout:
                    pass
            try:
                self.messages.put(json.loads(b"".join(chunks).decode("utf-8")))
            except ValueError:
                continue

    def close(self) -> None:
        self._stop.set()
        self._thread.join(timeout=2)
        self._srv.close()


class TTSClient:
    def __init__(self, host: str = "127.0.0.1", send_port: int = SEND_PORT, listen_port: int = LISTEN_PORT,
                 timeout: float = 5.0, late_grace: float = 8.0):
        self.host, self.send_port, self.listen_port, self.timeout = host, send_port, listen_port, timeout
        # a busy TTS (31/10: 5 s timeouts in pairs, the second call queued behind the first) still answers: after the
        # timeout the same request gets this long to reply before it is given up (a later call would find it busy too)
        self.late_grace = late_grace
        self.listener: Listener | None = None
        self._events: list[dict] = []        # buttons pressed while we waited for a Lua reply
        self._salt = int.from_bytes(os.urandom(3), "big") * 100000   # ids of this run different from those of other runs
        self._seq = itertools.count(1)   # rid = salt + n (< 1e15, exact as a float)
        self.reloads = 0                     # messageID 1 received (TTS reloaded the game)
        self.foreign_errors: deque[str] = deque(maxlen=50)   # Lua errors that are not from our request
        self.graces = 0                      # calls that went past their deadline and kept waiting for their reply
        self.stale_replies = 0               # replies dropped for not matching the request in progress
        self._calling = False                # inside call_lua: a click arriving now brings a table older than its reply
        self.calls = 0                       # Lua messages sent (each costs ~0.5 s in real TTS)
        self.call_seconds = 0.0              # total time waiting for replies
        self.trace: Callable[[str], None] | None = None     # with --timing: one line per call

    def start_listening(self) -> Listener:
        if self.listener is None:
            self.listener = Listener(self.host, self.listen_port)
        return self.listener

    def close(self) -> None:
        if self.listener:
            self.listener.close()
            self.listener = None

    def send(self, payload: dict) -> None:
        if payload.get("messageID") not in ALLOWED_OUT:
            raise UnsafeMessage(f"messageID {payload.get('messageID')!r} not allowed (only 2 and 3)")
        if payload["messageID"] == MSG_EXECUTE and not is_sendable(payload.get("script", "")):
            raise UnsafeMessage("only Lua generated by the builders of sparring.tts.lua is sent")
        data = json.dumps(payload).encode("utf-8")
        # each message opens a short connection: on Windows the pool of ephemeral ports runs out (WinError 10048)
        # while the previous ones are still in TIME_WAIT; it retries for a while instead of failing (like FakeTTS.push)
        for attempt in range(PORT_RETRIES):
            try:
                with socket.create_connection((self.host, self.send_port), timeout=self.timeout) as s:
                    s.sendall(data)
                return
            except OSError as e:
                if getattr(e, "winerror", None) != WSAEADDRINUSE or attempt == PORT_RETRIES - 1:
                    raise
                time.sleep(PORT_RETRY_WAIT)

    def send_custom(self, data) -> None:
        self.send({"messageID": MSG_CUSTOM, "customMessage": data})

    def execute_lua(self, script: str, guid: str = "-1") -> None:
        self.send({"messageID": MSG_EXECUTE, "guid": guid, "script": script})

    def _absorb(self, msg: dict) -> bool:
        """Handles what is not a reply to a request (buttons, reload, foreign errors). True if it consumed it.

        TTS does not send messageID 5: replies arrive as messageID 4 with `sparring_reply` in the message."""
        kind = msg.get("messageID")
        if kind == IN_CUSTOM:
            data = msg.get("customMessage")
            if isinstance(data, dict) and "sparring_reply" in data:
                return False
            if self._calling and isinstance(data, dict) and "snapshot" in data:
                data = {k: v for k, v in data.items() if k != "snapshot"}      # table older than the write in progress
            self._events.append(data)
        elif kind == IN_NEW_GAME:
            self.reloads += 1
        elif kind == IN_ERROR:
            # A failure of our scripts comes back as a reply with `err` (they run inside pcall); a
            # stray messageID 3 is from another script of the game and cannot be attributed to this call.
            self.foreign_errors.append(str(msg.get("error", msg)))
        return True                                   # prints (2), saves (6), returns (5): nothing to do

    def take_reload(self) -> bool:
        """True (once) if TTS reloaded the game since the last query."""
        seen, self.reloads = self.reloads > 0, 0
        return seen

    def call_lua(self, script: str, guid: str = "-1", timeout: float | None = None):
        """Runs Lua and waits for its reply, counting the call and its time (see `_call_lua`)."""
        started = time.monotonic()
        self._calling = True
        try:
            return self._call_lua(script, guid, timeout)
        finally:
            self._calling = False
            took = time.monotonic() - started
            self.calls += 1
            self.call_seconds += took
            if self.trace is not None:
                self.trace(f"{took * 1000:6.0f} ms  {script.split(chr(10), 1)[0].removeprefix('-- sparring:')}")

    def _call_lua(self, script: str, guid: str = "-1", timeout: float | None = None):
        """Runs Lua and waits for ITS reply (messageID 4 with `sparring_reply` equal to the request id).

        Before sending, the queue is emptied (late replies of calls that already timed out); a reply
        with another id is dropped and a Lua error is only this call's if it comes back with its id."""
        if not is_sendable(script):
            raise UnsafeMessage("only Lua generated by the builders of sparring.tts.lua is sent")
        listener = self.start_listening()
        while True:
            try:
                msg = listener.messages.get_nowait()
            except queue.Empty:
                break
            if not self._absorb(msg):
                self.stale_replies += 1
        rid = self._salt + next(self._seq)
        self.execute_lua(lua.request(script, rid), guid)
        deadline = time.monotonic() + (timeout or self.timeout)
        graced = self.late_grace <= 0
        while True:
            try:
                msg = listener.messages.get(timeout=max(0.0, deadline - time.monotonic()))
            except queue.Empty:
                if not graced:
                    graced, deadline = True, time.monotonic() + self.late_grace
                    self.graces += 1
                    continue
                raise TimeoutError(t("err.tts_no_value")) from None
            if self._absorb(msg):
                continue
            data = msg["customMessage"]
            reply = data["sparring_reply"]
            if isinstance(reply, bool) or not isinstance(reply, (int, float)) or int(reply) != rid:
                self.stale_replies += 1               # reply to an earlier call (timeout)
                continue
            if "err" in data:
                raise TTSLuaError(data["err"])
            value = data.get("value")
            try:
                return json.loads(value) if isinstance(value, str) else value
            except ValueError:
                return value

    def poll_events(self) -> list[dict]:
        """Human button presses (sendExternalMessage -> messageID 4), without blocking."""
        out, self._events = self._events, []
        if self.listener is None:
            return out
        while True:
            try:
                msg = self.listener.messages.get_nowait()
            except queue.Empty:
                break
            if not self._absorb(msg):
                self.stale_replies += 1               # late reply to a call that already timed out: dropped
        out.extend(self._events)
        self._events = []
        return out
